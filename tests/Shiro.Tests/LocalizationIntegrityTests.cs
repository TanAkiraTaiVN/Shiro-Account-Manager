    [Collection("StaticSeams")]
    public class LocalizationIntegrityTests
    {
        private static string FindRepoRoot()
        {
            var dir = new DirectoryInfo(AppContext.BaseDirectory);
            while (dir != null)
            {
                if (File.Exists(Path.Combine(dir.FullName, "Shiro.sln")))
                    return dir.FullName;
                dir = dir.Parent;
            }
            throw new InvalidOperationException("Shiro.sln not found");
        }

        private static string ViJsonPath => Path.Combine(FindRepoRoot(), "src", "Shiro", "Resources", "Strings", "vi.json");
        private static string EnJsonPath => Path.Combine(FindRepoRoot(), "src", "Shiro", "Resources", "Strings", "en.json");

        private static IEnumerable<string> SourceFiles(string relativeDir, string searchPattern)
        {
            var dir = Path.Combine(FindRepoRoot(), relativeDir);
            return Directory.GetFiles(dir, searchPattern, SearchOption.AllDirectories)
                .Where(f => !f.Contains(@"\bin\") && !f.Contains(@"\obj\") && !f.EndsWith(".g.cs"));
        }

        [Fact]
        public void LocalizationKeys_ShouldNotUseAutoGeneratedNames()
        {
            var hits = SourceFiles("src/Shiro", "*.cs").Concat(SourceFiles("src/Shiro", "*.axaml"))
                .Concat(new[] { ViJsonPath, EnJsonPath })
                .Where(f => File.ReadAllText(f).Contains("Auto_")).ToList();
            Assert.Empty(hits);
        }

        [Fact]
        public void EveryReferencedKey_ExistsInBothDictionaries()
        {
            var viJson = File.ReadAllText(ViJsonPath);
            var enJson = File.ReadAllText(EnJsonPath);
            var viDict = JsonSerializer.Deserialize<Dictionary<string, string>>(viJson)!;
            var enDict = JsonSerializer.Deserialize<Dictionary<string, string>>(enJson)!;

            var viKeys = new HashSet<string>(viDict.Keys, StringComparer.OrdinalIgnoreCase);
            var enKeys = new HashSet<string>(enDict.Keys, StringComparer.OrdinalIgnoreCase);

            var csFiles = SourceFiles("src/Shiro", "*.cs");
            var axamlFiles = SourceFiles("src/Shiro", "*.axaml");

            var referencedKeys = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            var csRegex = new Regex(@"(?:LocalizationService|Loc)\.(?:Get|Format)\s*\(\s*""([^""]+)""");
            foreach (var file in csFiles)
            {
                string content = File.ReadAllText(file);
                foreach (Match match in csRegex.Matches(content))
                {
                    referencedKeys.Add(match.Groups[1].Value);
                }
            }

            var axamlRegex = new Regex(@"\{DynamicResource\s+([A-Za-z0-9_.]+)\}");
            foreach (var file in axamlFiles)
            {
                string content = File.ReadAllText(file);
                foreach (Match match in axamlRegex.Matches(content))
                {
                    string key = match.Groups[1].Value;
                    if (key.EndsWith("Brush", StringComparison.Ordinal) ||
                        key.EndsWith("Color", StringComparison.Ordinal) ||
                        key.Contains("Theme", StringComparison.Ordinal) ||
                        key.Contains("Font", StringComparison.Ordinal))
                    {
                        continue;
                    }

                    string lookupKey = key.StartsWith("Loc_", StringComparison.Ordinal) ? key.Substring(4) : key;
                    referencedKeys.Add(lookupKey);
                }
            }

            var missingInVi = referencedKeys.Where(k => !viKeys.Contains(k)).ToList();
            var missingInEn = referencedKeys.Where(k => !enKeys.Contains(k)).ToList();

            Assert.True(missingInVi.Count == 0, $"Keys missing in vi.json ({missingInVi.Count}): {string.Join(", ", missingInVi)}");
            Assert.True(missingInEn.Count == 0, $"Keys missing in en.json ({missingInEn.Count}): {string.Join(", ", missingInEn)}");
        }

        [Fact]
        public void EveryViKey_HasNonEmptyEnglishValue()
        {
            var repoRoot = FindRepoRoot();
            var stringsDir = Path.Combine(repoRoot, "src", "Shiro", "Resources", "Strings");
            var viJson = File.ReadAllText(Path.Combine(stringsDir, "vi.json"));
            var enJson = File.ReadAllText(Path.Combine(stringsDir, "en.json"));
            var viDict = JsonSerializer.Deserialize<Dictionary<string, string>>(viJson)!;
            var enDict = JsonSerializer.Deserialize<Dictionary<string, string>>(enJson)!;

            var missingOrEmpty = viDict.Keys
                .Where(k => !enDict.TryGetValue(k, out var val) || string.IsNullOrWhiteSpace(val))
                .ToList();

            Assert.Empty(missingOrEmpty);
        }

        [Fact]
        public void AccountViewModel_ViewBanButtonText_FollowsLanguageAndRaisesChange()
        {
            try
            {
                var vm = new AccountViewModel(new Account { Username = "u" });
                var raised = new List<string?>();
                vm.PropertyChanged += (_, e) => raised.Add(e.PropertyName);
                LocalizationService.SetLanguage(AppLanguage.English, saveSetting: false);
                vm.NotifyLanguageChanged();
                Assert.Equal("View Ban", vm.ViewBanButtonText);
                LocalizationService.SetLanguage(AppLanguage.Vietnamese, saveSetting: false);
                vm.NotifyLanguageChanged();
                Assert.Equal("Xem lệnh cấm", vm.ViewBanButtonText);
                Assert.Contains(nameof(AccountViewModel.ViewBanButtonText), raised);
            }
            finally
            {
                LocalizationService.SetLanguage(AppLanguage.Vietnamese, saveSetting: false);
            }
        }

        [Fact]
        public void Format_WithMismatchedPlaceholdersOrBraces_DoesNotThrow()
        {
            try
            {
                LocalizationService.SetLanguage(AppLanguage.English, saveSetting: false);
                // no args -> template returned unformatted
                Assert.Equal("Player '{0}' was not found in current public servers.", LocalizationService.Format("ServerList.PlayerNotFound"));
                // extra args are ignored by string.Format
                Assert.Equal("Player 'a' was not found in current public servers.", LocalizationService.Format("ServerList.PlayerNotFound", "a", "b"));
                // missing key -> key returned (Get falls back to key)
                Assert.Equal("__missing_key__", LocalizationService.Format("__missing_key__", "x"));
                // template with literal brace and an arg -> SafeFormat must not throw
                var ex = Record.Exception(() => LocalizationService.Format("__missing_key__", "{bad", 1));
                Assert.Null(ex);
            }
            finally
            {
                LocalizationService.SetLanguage(AppLanguage.Vietnamese, saveSetting: false);
            }
        }

        [Fact]
        public void LocalizationService_Format_HandlesMissingKeysAndMismatchedPlaceholdersSafely()
        {
            LocalizationService.EnsureCoreKeys();
            string missing = LocalizationService.Format("NonExistent_Key_999", "fallback {0}", "A", "B");
            Assert.Contains("A", missing);

            string malformed = LocalizationService.Format("NonExistent_Key_999", "bad {0} {5}", "onlyOne");
            Assert.False(string.IsNullOrWhiteSpace(malformed));
        }

        // Intentional bilingual UI labels plus the U+0111 ('đ') Unicode folding constant used by CommandPaletteCoordinator.NormalizeSearchText.
        private static readonly HashSet<string> AllowedBilingualKeysInEnJson = new(StringComparer.OrdinalIgnoreCase)
        {
            "Cap_Language",
            "Set_Language_EN",
            "Set_Language_VN",
            "CommandPalette.CharDWithStroke"
        };

        private static readonly Regex VietnameseDiacriticRegex = new(
            "[àáạảãâầấậẩẫăằắặẳẵèéẹẻẽêềếệểễìíịỉĩòóọỏõôồốộổỗơờớợởỡùúụủũưừứựửữỳýỵỷỹđÀÁẠẢÃÂẦẤẬẨẪĂẰẮẶẲẴÈÉẸẺẼÊỀẾỆỂỄÌÍỊỈĨÒÓỌỎÕÔỒỐỘỔỖƠỜỚỢỞỠÙÚỤỦŨƯỪỨỰỬỮỲÝỴỶỸĐ]",
            RegexOptions.Compiled);

        private static readonly Regex AxamlCommentRegex = new(
            @"<!--[\s\S]*?-->",
            RegexOptions.Compiled);

        [Fact]
        public void AxamlFiles_ShouldNotContain_HardcodedVietnameseText()
        {
            var violations = new List<string>();

            foreach (var file in SourceFiles("src/Shiro", "*.axaml"))
            {
                string raw = File.ReadAllText(file);
                string withoutComments = AxamlCommentRegex.Replace(raw, string.Empty);
                string[] lines = withoutComments.Split('\n');
                for (int i = 0; i < lines.Length; i++)
                {
                    if (VietnameseDiacriticRegex.IsMatch(lines[i]))
                    {
                        violations.Add($"{Path.GetFileName(file)}:{i + 1} -> {lines[i].Trim()}");
                    }
                }
            }

            Assert.True(violations.Count == 0,
                $"Found hardcoded Vietnamese text in AXAML files ({violations.Count}):\n{string.Join("\n", violations.Take(40))}");
        }

        private static readonly Regex FormatPlaceholderRegex = new(
            @"\{\d+(?:[:,][^}]+)?\}",
            RegexOptions.Compiled);

        [Fact]
        public void EnJson_ShouldNotContainUntranslatedVietnameseDiacritics()
        {
            var enDict = JsonSerializer.Deserialize<Dictionary<string, string>>(File.ReadAllText(EnJsonPath))!;
            var untranslated = enDict
                .Where(kvp => !AllowedBilingualKeysInEnJson.Contains(kvp.Key) && VietnameseDiacriticRegex.IsMatch(kvp.Value))
                .Select(kvp => $"{kvp.Key}: {kvp.Value}")
                .ToList();

            Assert.True(untranslated.Count == 0,
                $"Found {untranslated.Count} untranslated Vietnamese entries in en.json:\n{string.Join("\n", untranslated.Take(30))}");
        }

        [Fact]
        public void EnJson_And_ViJson_ShouldHaveMatchingFormatPlaceholders()
        {
            var viDict = JsonSerializer.Deserialize<Dictionary<string, string>>(File.ReadAllText(ViJsonPath))!;
            var enDict = JsonSerializer.Deserialize<Dictionary<string, string>>(File.ReadAllText(EnJsonPath))!;

            var mismatches = new List<string>();
            foreach (var (key, viVal) in viDict)
            {
                if (!enDict.TryGetValue(key, out string? enVal)) continue;
                var viTokens = FormatPlaceholderRegex.Matches(viVal).Select(m => m.Value).OrderBy(x => x).ToArray();
                var enTokens = FormatPlaceholderRegex.Matches(enVal).Select(m => m.Value).OrderBy(x => x).ToArray();
                if (!viTokens.SequenceEqual(enTokens))
                {
                    mismatches.Add($"{key}: vi=[{string.Join(", ", viTokens)}] vs en=[{string.Join(", ", enTokens)}]");
                }
            }

            Assert.True(mismatches.Count == 0,
                $"Format placeholder mismatches between vi.json and en.json:\n{string.Join("\n", mismatches)}");
        }

        [Fact]
        public void CommandPalette_NormalizeSearchText_FoldsDWithStroke_WhenLanguageIsEnglish()
        {
            try
            {
                LocalizationService.SetLanguage(AppLanguage.English, saveSetting: false);
                Assert.Equal("dong", CommandPaletteCoordinator.NormalizeSearchText("Đóng"));
                Assert.Equal("dang nhap lai", CommandPaletteCoordinator.NormalizeSearchText("đăng nhập lại"));
            }
            finally
            {
                LocalizationService.SetLanguage(AppLanguage.Vietnamese, saveSetting: false);
            }
        }
    }
